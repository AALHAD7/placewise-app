// R4: eval runner + baseline score on the current LIVE chunks.
//
// Calls the real lib functions the routes use - not a copy, not an HTTP
// round-trip - per .claude/skills/rag-eval/SKILL.md ("Runner ... calls the
// same functions the routes use, not a copy"). ENABLE_CONSULTING_RAG_V2 is
// read but never set here: this measures exactly what a student sees on the
// live site today (the flag is off by default - see frameworksGrounding.js
// and routes/guesstimates.js). Run with `node backend/eval/run_eval.js
// [label]` from anywhere; `label` defaults to "baseline".
//
// What each `feature` value in questions.jsonl actually has live right now
// (confirmed by reading the code, not assumed - see log.md's R4 entry):
//
//   - frameworks: the v1 path (frameworksGrounding.js's findGrounding, via
//     withGroundedExamples - the exact function routes/frameworks.js calls)
//     queries document_chunks via match_document_chunks. That function is
//     built for *seeded* framework rows ({name, domain, subdomain}) from the
//     `frameworks` table, not arbitrary free-text questions. This runner
//     maps each question onto a synthetic, never-persisted framework row
//     ({name: question text, domain: question.domain, id: a fresh random
//     uuid, grounded_checked_at: null}) so the exact same query string
//     findGrounding builds for a real row (`${fw.name} framework diagram
//     case study real example application ...`) gets built from the
//     question's own text. withGroundedExamples does write its result back
//     to the `frameworks` table at the end (`UPDATE ... WHERE id = <uuid>`)
//     - confirmed live before relying on it (see log.md) that this matches
//     zero rows and is a no-op: it can't create or touch a real row.
//
//   - guesstimates: routes/guesstimates.js gates every response behind
//     ENABLE_CONSULTING_RAG_V2 and returns {available:false,
//     reason:"feature_disabled"} whenever it's off (the live default). This
//     runner reads that exact same flag rather than importing
//     guesstimateRetrieval.js's lib functions directly - calling those
//     directly would bypass the route's gate and fabricate a result no
//     student can actually get today.
//
//   - qa / role / company: no grounded retrieval route exists for these at
//     all. chat.js is a generic ungrounded passthrough to Gemini (no
//     casebook lookup, no citations, no coverage check) - routing these
//     questions through it would test "does Gemini know things", not RAG,
//     and routing them through groundedConsultingLookup would test the new
//     (flag-gated, not-live) v2 pipeline instead of today's live behavior.
//     Recorded plainly as "no_rag_route" with every check failed, rather
//     than inventing either path.
//
// Faithfulness is judged by a cheap Gemini model (generateJSON's default
// cascade - flash-lite tiers only, no `allowEscalation`) and only called
// when something was actually retrieved; there is nothing to judge for a
// dark feature or a correct empty result, and calling the judge anyway
// would just burn budget for no signal. Retrieval, citations, coverage
// labels and diagram-intactness are all checked in code below, per the
// skill's "check retrieval, citations, labels and diagrams with code, not
// an LLM."

import "dotenv/config";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import crypto from "node:crypto";
import { withGroundedExamples } from "../src/lib/frameworksGrounding.js";
import { generateJSON } from "../src/lib/gemini.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const QUESTIONS_PATH = path.join(__dirname, "questions.jsonl");
const RESULTS_DIR = path.join(__dirname, "results");

const CONSULTING_RAG_V2_ENABLED = process.env.ENABLE_CONSULTING_RAG_V2 === "true";

const GUESSTIMATES_REASON =
  'ENABLE_CONSULTING_RAG_V2 is not "true" - GET /api/guesstimates/random and /ask both ' +
  'return {available:false, reason:"feature_disabled"} unconditionally (routes/guesstimates.js). ' +
  "This feature does not exist for a student on the live site right now, for any question.";

const NO_RAG_REASON =
  'No grounded retrieval route exists for the "{feature}" feature (checked backend/src/routes/*.js). ' +
  "chat.js is an ungrounded Gemini passthrough with no casebook lookup, no citation, and no " +
  "coverage check at all. Recorded as a flat absence, not simulated.";

const CHECK_NAMES = ["retrieval_hit", "faithfulness", "citations", "coverage_label", "diagram_intact", "must_include"];

const callCounts = { embedding: 0, judge: 0 };

function loadQuestions() {
  if (!existsSync(QUESTIONS_PATH)) {
    console.error(`[run_eval] ${QUESTIONS_PATH} does not exist. Stopping - questions are not generated by this runner.`);
    process.exit(1);
  }
  const raw = readFileSync(QUESTIONS_PATH, "utf8").trim();
  if (!raw) {
    console.error(`[run_eval] ${QUESTIONS_PATH} is empty. Stopping.`);
    process.exit(1);
  }
  return raw.split("\n").map((line, i) => {
    try {
      return JSON.parse(line);
    } catch (err) {
      console.error(`[run_eval] line ${i + 1} is not valid JSON: ${err.message}`);
      process.exit(1);
    }
  });
}

// Strips a known extension and normalizes for comparing a retrieved
// document_chunks.source_file ("The FMS Consulting Casebook 2021-22.txt")
// against questions.jsonl's extension-less expected_source ("The FMS
// Consulting Casebook 2021-22") - document_chunks carries both .pdf (v1
// re-ingestion attempt, 0 active rows for every Consulting casebook checked)
// and .txt (an older pipeline, which does have active rows) copies of the
// same casebook under different source_file values; neither carries a page
// number.
function stem(name) {
  return (name || "").replace(/\.(pdf|txt)$/i, "").trim().toLowerCase();
}

function sourceMatches(retrievedFile, expectedSource) {
  if (!expectedSource) return false;
  const a = stem(retrievedFile);
  const b = stem(expectedSource);
  return !!a && !!b && (a === b || a.includes(b) || b.includes(a));
}

async function judgeFaithfulness(question, excerptText) {
  callCounts.judge++;
  try {
    const parsed = await generateJSON({
      system:
        "You are a strict grader checking whether a casebook excerpt shown VERBATIM to a student " +
        "actually, faithfully and relevantly answers their interview-prep question. The excerpt " +
        "cannot contain any claim beyond itself (it is the literal source text, not a generated " +
        "answer) - your only job is to judge whether it is genuinely on-topic and answers what was " +
        "asked, not just coincidentally sharing vocabulary with the question. Respond with ONLY a " +
        'JSON object, no markdown fences: {"verdict": "faithful" or "unfaithful", "reasoning": ' +
        '"one sentence explaining your judgment"}',
      prompt: `Question: ${question}\n\nExcerpt shown to the student:\n"""${excerptText.slice(0, 2000)}"""\n\nDoes this excerpt faithfully and relevantly answer the question?`,
      maxTokens: 200,
      feature: "eval-judge-r4"
    });
    const verdict = parsed.verdict === "faithful" ? "faithful" : "unfaithful";
    return { verdict, reasoning: String(parsed.reasoning || "") };
  } catch (err) {
    return { verdict: "error", reasoning: `Judge call failed: ${err.message}` };
  }
}

async function evalFrameworksQuestion(q) {
  const syntheticFw = {
    id: crypto.randomUUID(),
    name: q.question,
    domain: q.domain,
    subdomain: null,
    grounded_checked_at: null
  };
  callCounts.embedding++;
  const [result] = await withGroundedExamples([syntheticFw]);
  const example = result.grounded_example || null;
  const image = result.grounded_image || null;
  const found = example || image;
  const retrievedFile = example?.sourceFile || image?.sourceFile || null;

  const checks = {};

  if (!q.covered) {
    checks.retrieval_hit = { verdict: "n/a", reason: "covered:false - no expected_source to match against." };
  } else if (!found) {
    checks.retrieval_hit = {
      verdict: "fail",
      reason: "Nothing retrieved above the similarity threshold for a question the casebooks should cover."
    };
  } else {
    const matched = sourceMatches(retrievedFile, q.expected_source);
    checks.retrieval_hit = {
      verdict: matched ? "pass" : "fail",
      reason: matched
        ? `Retrieved from "${retrievedFile}", matching expected_source "${q.expected_source}". ` +
          `NOTE: document_chunks has no page column at all, so expected_pages ` +
          `(${JSON.stringify(q.expected_pages)}) could not be verified - a structural gap in the ` +
          "live v1 table, not a per-question miss."
        : `Retrieved from "${retrievedFile}", which does not match expected_source "${q.expected_source}".`
    };
  }

  if (!found) {
    checks.faithfulness = { verdict: "n/a", reason: "Nothing was retrieved, so there is nothing to judge." };
  } else {
    const excerptText = [example?.excerpt, image?.caption].filter(Boolean).join("\n\n");
    const judged = await judgeFaithfulness(q.question, excerptText);
    checks.faithfulness = {
      verdict: judged.verdict === "faithful" ? "pass" : judged.verdict === "unfaithful" ? "fail" : "error",
      reason: judged.reasoning
    };
  }

  if (!found) {
    checks.citations = { verdict: "n/a", reason: "Nothing retrieved, so no citation is shown either way." };
  } else {
    checks.citations = {
      verdict: "fail",
      reason:
        `v1's citation is only a source filename ("${retrievedFile}") - no page number at all. ` +
        "CLAUDE.md requires citations of (school, casebook, page); document_chunks has no page " +
        "column (confirmed: selecting it throws 'column document_chunks.page_start does not " +
        "exist'). This is structural and true for every v1 citation, not specific to this question."
    };
  }

  if (q.covered) {
    checks.coverage_label = {
      verdict: found ? "pass" : "fail",
      reason: found
        ? "A grounded excerpt/image was shown for a question the casebooks should cover."
        : "Nothing was shown for a question the casebooks should cover - the student gets no answer at all."
    };
  } else {
    checks.coverage_label = {
      verdict: found ? "fail" : "pass",
      reason: found
        ? `Something was shown for a question that should NOT be covered (source: "${retrievedFile}").`
        : "Correctly showed nothing below threshold. NOTE: this only confirms 'nothing shown' - the " +
          "live Frameworks UI (frontend-react/src/pages/FrameworksPage.tsx) has no 'not from the " +
          "casebooks - AI-generated' fallback/label at all, so CLAUDE.md's 'say so plainly, then " +
          "give a labelled general answer' is not met by this path regardless of this result."
    };
  }

  if (!image) {
    checks.diagram_intact = { verdict: "n/a", reason: "No image/diagram was retrieved for this question." };
  } else {
    const intact = !!(image.url && image.caption);
    checks.diagram_intact = {
      verdict: intact ? "pass" : "fail",
      reason: intact
        ? "Diagram block present (url + caption). NOTE: image.url is a raw document_chunks.image_url " +
          "Storage URL served through an optionalAuth route with no admin gate - CLAUDE.md requires " +
          "page images stay admin-only and their storage URLs never reach non-admin users; this path " +
          "exposes one directly whenever a diagram scores above threshold."
        : "An image row matched but is missing url or caption."
    };
  }

  if (!q.must_include || q.must_include.length === 0) {
    checks.must_include = { verdict: "n/a", reason: "No must_include terms specified for this question." };
  } else if (!found) {
    checks.must_include = { verdict: "fail", reason: "Nothing retrieved, so none of the must_include terms could be present." };
  } else {
    const haystack = [example?.excerpt, image?.caption].filter(Boolean).join("\n\n").toLowerCase();
    const missing = q.must_include.filter(t => !haystack.includes(String(t).toLowerCase()));
    checks.must_include = {
      verdict: missing.length === 0 ? "pass" : "fail",
      reason: missing.length === 0 ? "All must_include terms found in the retrieved text." : `Missing: ${missing.join(", ")}`
    };
  }

  return {
    checks,
    retrieved: {
      example: example ? { sourceFile: example.sourceFile, similarity: example.similarity, excerpt: example.excerpt } : null,
      image: image ? { sourceFile: image.sourceFile, similarity: image.similarity, caption: image.caption, url: image.url } : null
    }
  };
}

function evalDarkFeature(reasonTemplate, feature) {
  const reason = reasonTemplate.replace("{feature}", feature);
  const checks = {};
  for (const name of CHECK_NAMES) checks[name] = { verdict: "fail", reason };
  return { checks, retrieved: null };
}

function overallVerdict(checks) {
  const applicable = Object.values(checks).filter(c => c.verdict !== "n/a");
  if (applicable.length === 0) return "n/a";
  return applicable.every(c => c.verdict === "pass") ? "pass" : "fail";
}

function summarize(results) {
  const perCheck = {};
  for (const name of CHECK_NAMES) perCheck[name] = { pass: 0, fail: 0, error: 0, na: 0 };

  for (const r of results) {
    for (const name of CHECK_NAMES) {
      const v = r.checks[name].verdict;
      if (v === "pass") perCheck[name].pass++;
      else if (v === "fail") perCheck[name].fail++;
      else if (v === "error") perCheck[name].error++;
      else perCheck[name].na++;
    }
  }

  const scored = results.filter(r => r.overall !== "n/a");
  const overallPass = scored.filter(r => r.overall === "pass").length;

  return {
    totalQuestions: results.length,
    overallPassRate: scored.length ? overallPass / scored.length : null,
    overallPass,
    overallScored: scored.length,
    perCheck
  };
}

function findPreviousResultsFile() {
  if (!existsSync(RESULTS_DIR)) return null;
  const files = readdirSync(RESULTS_DIR).filter(f => f.endsWith(".json")).sort();
  return files.length ? path.join(RESULTS_DIR, files[files.length - 1]) : null;
}

function diffAgainstPrevious(results, previousPath) {
  if (!previousPath) {
    return { note: "No previous results file exists in backend/eval/results/ - this is the first eval run, there is nothing to regress against.", regressions: [] };
  }
  const previous = JSON.parse(readFileSync(previousPath, "utf8"));
  const prevById = Object.fromEntries((previous.results || []).map(r => [r.id, r]));
  const regressions = [];
  for (const r of results) {
    const prev = prevById[r.id];
    if (prev && prev.overall === "pass" && r.overall !== "pass") {
      regressions.push({ id: r.id, question: r.question, was: prev.overall, now: r.overall });
    }
  }
  return { note: `Compared against ${path.basename(previousPath)}.`, regressions };
}

async function main() {
  const label = process.argv[2] || "baseline";

  if (CONSULTING_RAG_V2_ENABLED) {
    console.error(
      "[run_eval] ENABLE_CONSULTING_RAG_V2=true in this environment - refusing to run. " +
      "This runner measures the LIVE (flag-off) behavior; unset the flag before running a baseline."
    );
    process.exit(1);
  }

  const questions = loadQuestions();
  console.log(`[run_eval] Loaded ${questions.length} questions from ${QUESTIONS_PATH}.`);

  const results = [];
  for (const q of questions) {
    let evalResult;
    if (q.feature === "frameworks") {
      evalResult = await evalFrameworksQuestion(q);
    } else if (q.feature === "guesstimates") {
      evalResult = evalDarkFeature(GUESSTIMATES_REASON, q.feature);
    } else {
      evalResult = evalDarkFeature(NO_RAG_REASON, q.feature);
    }
    const overall = overallVerdict(evalResult.checks);
    const row = {
      id: q.id,
      feature: q.feature,
      covered: q.covered,
      question: q.question,
      expected_source: q.expected_source || null,
      expected_pages: q.expected_pages || [],
      must_include: q.must_include || [],
      overall,
      checks: evalResult.checks,
      retrieved: evalResult.retrieved
    };
    results.push(row);
    console.log(`  ${q.id} [${q.feature}, covered:${q.covered}] -> ${overall}`);
  }

  const summary = summarize(results);
  const previousPath = findPreviousResultsFile();
  const comparison = diffAgainstPrevious(results, previousPath);

  mkdirSync(RESULTS_DIR, { recursive: true });
  // Local date, not UTC (toISOString() would roll back to the previous day
  // for IST evenings) - matches how Aalhad names everything else here.
  const now = new Date();
  const dateStr = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}-${String(now.getDate()).padStart(2, "0")}`;
  const jsonPath = path.join(RESULTS_DIR, `${dateStr}-${label}.json`);
  const mdPath = path.join(RESULTS_DIR, `${dateStr}-${label}.md`);

  const output = {
    runAt: new Date().toISOString(),
    label,
    enableConsultingRagV2: CONSULTING_RAG_V2_ENABLED,
    callCounts,
    summary,
    comparison,
    results
  };
  writeFileSync(jsonPath, JSON.stringify(output, null, 2));

  const md = buildMarkdownSummary(output);
  writeFileSync(mdPath, md);

  console.log(`\n[run_eval] Overall: ${summary.overallPass}/${summary.overallScored} scored questions pass (${summary.totalQuestions} total, ${summary.totalQuestions - summary.overallScored} n/a).`);
  console.log(`[run_eval] Gemini calls: ${callCounts.embedding} embedding, ${callCounts.judge} judge.`);
  console.log(`[run_eval] Wrote ${jsonPath}`);
  console.log(`[run_eval] Wrote ${mdPath}`);
}

function pct(n, d) {
  return d ? `${Math.round((n / d) * 100)}%` : "n/a";
}

function buildMarkdownSummary(output) {
  const { summary, comparison, results, callCounts, enableConsultingRagV2 } = output;
  const lines = [];
  lines.push(`# RAG eval — ${output.label} (${output.runAt})`);
  lines.push("");
  lines.push(`ENABLE_CONSULTING_RAG_V2: ${enableConsultingRagV2} (must be false for a live-site baseline)`);
  lines.push("");
  lines.push(`**Overall pass rate:** ${summary.overallPass}/${summary.overallScored} (${pct(summary.overallPass, summary.overallScored)}) of ${summary.totalQuestions} total questions.`);
  lines.push("");
  lines.push("## Per-check pass rate (pass / (pass+fail+error), n/a excluded)");
  lines.push("");
  lines.push("| Check | Pass | Fail | Error | N/A | Pass rate |");
  lines.push("|---|---|---|---|---|---|");
  for (const name of CHECK_NAMES) {
    const c = summary.perCheck[name];
    const denom = c.pass + c.fail + c.error;
    lines.push(`| ${name} | ${c.pass} | ${c.fail} | ${c.error} | ${c.na} | ${pct(c.pass, denom)} |`);
  }
  lines.push("");
  lines.push("## Per-feature breakdown");
  lines.push("");
  const byFeature = {};
  for (const r of results) {
    byFeature[r.feature] = byFeature[r.feature] || { pass: 0, scored: 0, total: 0 };
    byFeature[r.feature].total++;
    if (r.overall !== "n/a") {
      byFeature[r.feature].scored++;
      if (r.overall === "pass") byFeature[r.feature].pass++;
    }
  }
  lines.push("| Feature | Pass | Scored | Total |");
  lines.push("|---|---|---|---|");
  for (const [feature, c] of Object.entries(byFeature)) {
    lines.push(`| ${feature} | ${c.pass} | ${c.scored} | ${c.total} |`);
  }
  lines.push("");
  lines.push("## Regressions vs previous run");
  lines.push("");
  lines.push(comparison.note);
  if (comparison.regressions.length) {
    for (const reg of comparison.regressions) {
      lines.push(`- **${reg.id}** (${reg.was} -> ${reg.now}): ${reg.question}`);
    }
  }
  lines.push("");
  lines.push("## Gemini call counts");
  lines.push("");
  lines.push(`- Embedding calls (gemini-embedding-001, RETRIEVAL_QUERY): ${callCounts.embedding}`);
  lines.push(`- Faithfulness judge calls (flash-lite tier, generateJSON default cascade): ${callCounts.judge}`);
  lines.push("");
  lines.push("## Failing/worst questions");
  lines.push("");
  const failing = results.filter(r => r.overall === "fail");
  for (const r of failing) {
    lines.push(`### ${r.id} [${r.feature}, covered:${r.covered}]`);
    lines.push(`Q: ${r.question}`);
    for (const name of CHECK_NAMES) {
      const c = r.checks[name];
      if (c.verdict === "fail" || c.verdict === "error") {
        lines.push(`- **${name}** (${c.verdict}): ${c.reason}`);
      }
    }
    lines.push("");
  }
  return lines.join("\n");
}

main().catch(err => {
  console.error("[run_eval] Fatal error:", err);
  process.exit(1);
});
