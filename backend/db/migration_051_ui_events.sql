-- Migration 051: UI event tracking (clicks + section views)
-- Stores every individual click/view event raw (queryable later), separate from the
-- human-readable rollup that gets pushed to the "Engagement" Google Sheets tab
-- (backend/scripts/rollupUiEvents.js). Scope for now (2026-11-12): Frameworks, Q&A,
-- Guesstimates pages only - see log.md for why, and frontend src/lib/uiEvents.ts for the
-- tracker. Not an AI-backed table, no llm_call_log equivalent needed.

create table if not exists ui_events (
  id          uuid        primary key default gen_random_uuid(),
  user_id     uuid        references auth.users(id) on delete set null,
  -- Short client-generated id for guest sessions (localStorage, not PII) - lets "most
  -- active guest session" be distinguished from "every guest is the same bucket"
  -- without ever storing anything identifying.
  guest_label text,
  event_type  text        not null check (event_type in ('click', 'view')),
  -- Route path at the time of the event, e.g. "/frameworks", "/qa" - not the full URL
  -- (no query strings), so it doesn't leak anything incidental.
  page        text        not null,
  -- Human-labelled UI element/section, e.g. "framework-card:Porter's Five Forces",
  -- "ask-question-button" - defined per-instrumented component, not auto-derived from
  -- DOM structure (which would be unreadable and break on every markup change).
  section     text,
  metadata    jsonb,
  created_at  timestamptz not null default now()
);

create index if not exists ui_events_created_at_idx on ui_events (created_at);
create index if not exists ui_events_page_section_idx on ui_events (page, section);

-- RLS: service role only (backend uses service key) - same posture as every other
-- backend-only table in this app (practice_eval_cache, llm_call_log, ingest_*).
alter table ui_events enable row level security;

comment on table ui_events is
  'Raw click/view events from instrumented frontend pages. One row per event - '
  'the readable rollup (top-clicked elements, most-viewed sections) lives in the '
  '"Engagement" Google Sheets tab, generated by backend/scripts/rollupUiEvents.js, '
  'not as individual rows in this table.';
